const TRANSITIONS = {
  DRAFT: ['PAYMENT_PENDING', 'CANCELLED'],
  PAYMENT_PENDING: ['CONFIRMED', 'PAYMENT_FAILED', 'CANCELLED', 'REFUND_PENDING'],
  PAYMENT_FAILED: ['PAYMENT_PENDING', 'CONFIRMED', 'CANCELLED', 'REFUND_PENDING'],
  CONFIRMED: ['CANCELLED'],
  CANCELLED: ['REFUND_PENDING'],
  REFUND_PENDING: ['REFUNDED'],
  REFUNDED: [],
};
const canTransition = (from, to) => (TRANSITIONS[from] || []).includes(to);
module.exports = { TRANSITIONS, canTransition };
